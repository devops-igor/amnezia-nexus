// countRegisteredServers counts the panel server rows claiming this provider server.
func (f *awgConsumerFixture) countRegisteredServers(t *testing.T) int {
	t.Helper()
	servers, err := f.db.GetAllServers(context.Background())
	if err != nil {
		t.Fatalf("list servers: %v", err)
	}
	count := 0
	for k := range servers {
		if servers[k].Protocols == nil {
			continue
		}
		if provider, _ := servers[k].Protocols["provider"].(string); provider != "gigahost" {
			continue
		}
		if matchProviderServerID(servers[k].Protocols["provider_server_id"], f.providerServerID) {
			count++
		}
	}
	return count
}

// countEnrollments counts durable enrollment markers for this backend.
func (f *awgConsumerFixture) countEnrollments(t *testing.T) int {
	t.Helper()
	servers, err := f.db.GetAllServers(context.Background())
	if err != nil {
		t.Fatalf("list servers: %v", err)
	}
	marks, err := f.db.GetBackendPendingEnrollments(context.Background())
	if err != nil {
		t.Fatalf("read durable enrollment markers: %v", err)
	}
	count := 0
	for k := range servers {
		if servers[k].Protocols == nil {
			continue
		}
		if provider, _ := servers[k].Protocols["provider"].(string); provider != "gigahost" {
			continue
		}
		if matchProviderServerID(servers[k].Protocols["provider_server_id"], f.providerServerID) &&
			marks[servers[k].ID] {
			count++
		}
	}
	return count
}

// peerKeysAreRealKeyMaterial reports whether every identity the peer registered decoded to a
// full Curve25519 public key, so "the production path registered a peer" cannot be satisfied by
// an empty or truncated string.
func (p *awgConsumerPeer) peerKeysAreRealKeyMaterial() bool {
	p.mu.Lock()
	defer p.mu.Unlock()
	if len(p.clientPeers) == 0 {
		return false
	}
	for hexKey := range p.clientPeers {
		if len(hexKey) != 64 {
			return false
		}
	}
	return true
}
