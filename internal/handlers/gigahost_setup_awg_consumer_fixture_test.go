// newAWGConsumerJob builds the state a real purchase leaves - a purchase stamp and an
// encrypted managed credential, and nothing else - then lets the production background chain
// produce the association, the grant and the pin.
func newAWGConsumerJob(
	t *testing.T, orderID string, providerServerID int64, answerCanary bool,
) *awgConsumerFixture {
	t.Helper()

	env := newInstallEnv(t, models.ProtocolAWG)
	// One SSH identity for the whole job: the first-contact challenge and the install observe
	// the same peer, so the pin is preserved rather than re-pointed later.
	env.useAuthenticSSHBoundary()

	peer := startAWGConsumerPeer(t, answerCanary)
	// The installation records the dialect it deployed, which is what a real AWG install
	// records on the server row.
	installAWGConsumerDialect(env, peer)
	// The service learns about the backend through the provider, which is also the contract
	// the production enablement path uses to register the portal's peers on it.
	env.h.vpnSvc.SetAWGStatusProvider(&awgConsumerProvider{peer: peer})

	// The canary is the capture seam, installed before any enablement so the shared fixture's
	// success stub cannot answer a qualification question.
	observation := installAWGConsumerCanary(t, env, peer)

	// --- the purchase: stamp + credential, and nothing else -------------------------------
	key := newManagedTestKey(t)
	env.seedFreshPurchase(orderID, key)
	// The provider knows the order and its server; the ledger does not, which is exactly the
	// state after a purchase whose provisioning has just finished.
	env.providerServes(orderID, providerServerID, "127.0.0.1")
	purchases := newPurchaseCounter()
	env.provider.orderServerFn = purchases.refuse
	env.provider.orderServerSafeFn = purchases.refuse

	env.enableAutomaticSetup(true)
	env.startAutomatic(orderID, AutomaticGigahostSetupOptions{
		Protocol: models.ProtocolAWG,
		Port:     strconv.Itoa(peer.port),
	})

	// --- assert the starting state is genuinely bare --------------------------------------
	requireNoAuthorityYet(t, env, orderID, "before the production tracking pass")

	// --- production background consumers acquire everything --------------------------------
	if err := env.h.NewGigahostSetupTracker().RunOnce(context.Background()); err != nil {
		t.Fatalf("tracking pass: %v", err)
	}
	env.requireState(orderID, models.SetupStateReadyForSetup)

	order, found, err := env.db.GetGigahostOrder(context.Background(), orderID)
	if err != nil || !found {
		t.Fatalf("read order after tracking: found=%v err=%v", found, err)
	}
	if order.ServerID != providerServerID {
		t.Fatalf("the background pass did not record the provider server id: ledger has %d, want %d",
			order.ServerID, providerServerID)
	}
	if order.AssignedIP == "" {
		t.Fatal("the background pass did not record the provider address on the ledger")
	}
	granted := env.intent(orderID)
	if granted.HostTrustOrderID != orderID || granted.HostTrustServerID != providerServerID {
		t.Fatalf("the background pass did not acquire the scoped grant: order=%q server=%d",
			granted.HostTrustOrderID, granted.HostTrustServerID)
	}
	if granted.HostTrustGrantedAt.IsZero() {
		t.Fatal("the background pass did not record when the grant was issued")
	}
	if granted.HostFingerprint == "" {
		t.Fatal("the background pass did not pin a host identity")
	}
	requireNoFingerprintRewrite(t, granted.HostFingerprint, installFixtureFingerprint, "after tracking")

	return &awgConsumerFixture{
		installEnv:       env,
		peer:             peer,
		observation:      observation,
		orderID:          orderID,
		providerServerID: providerServerID,
		pinnedPresented:  granted.HostFingerprint,
		purchaseAttempts: purchases,
	}
}

// requireObservationCaptured fails when the qualification seam never ran the capture.
//
// This is the guard against a silent override: if the shared fixture's success stub were still
// answering, the probe would return nil without this fixture ever observing a device.
func (f *awgConsumerFixture) requireObservationCaptured(t *testing.T, when string) {
	t.Helper()
	obs := *f.observation
	if !obs.captured {
		t.Fatalf("%s: the qualification seam never ran the capture, so the canary was answered "+
			"by something other than the production probe", when)
	}
	logged := obs
	logged.canaryErr = nil
	t.Logf("%s: %s", when, logged.summary())
	t.Logf("%s: diagnosis: %s", when, logged.diagnosis())
}

// requireHealthyObservations asserts the pre-rollback observations a healthy AWG backend must
// show, naming each boolean so a remote-only failure identifies the boundary.
func (f *awgConsumerFixture) requireHealthyObservations(t *testing.T, when string) {
	t.Helper()
	obs := *f.observation
	if !obs.deviceFound {
		t.Fatalf("%s: no backend device was attached, so nothing was qualified", when)
	}
	if !obs.deviceIsAWGDevice {
		t.Fatalf("%s: the attached backend device is not the production AWG device", when)
	}
	if !obs.tunnelEndpointOK || !obs.endpointMatches {
		t.Fatalf("%s: the tunnel endpoint does not match the peer: tunnel=%t recorded=%t",
			when, obs.tunnelEndpointOK, obs.endpointMatches)
	}
	if !obs.dialect.allMatch() {
		t.Fatalf("%s: %s", when, obs.diagnosis())
	}
	if !obs.counters.i1Present {
		t.Fatalf("%s: %s", when, obs.diagnosis())
	}
	if !obs.counters.handshakeObserved {
		t.Fatalf("%s: %s", when, obs.diagnosis())
	}
	if !obs.counters.txPositive {
		t.Fatalf("%s: %s", when, obs.diagnosis())
	}
	if !obs.counters.rxPositive {
		t.Fatalf("%s: %s", when, obs.diagnosis())
	}
}

// requireHandshakeWithoutPayload asserts the negative's shape: the tunnel is established and
// the payload is what failed. Without the handshake observation the negative would be
// indistinguishable from a dead tunnel.
func (f *awgConsumerFixture) requireHandshakeWithoutPayload(t *testing.T, when string) {
	t.Helper()
	obs := *f.observation
	if !obs.deviceFound || !obs.deviceIsAWGDevice {
		t.Fatalf("%s: the negative did not reach the production AWG device", when)
	}
	if !obs.tunnelEndpointOK || !obs.endpointMatches {
		t.Fatalf("%s: the negative's endpoint does not match the peer: tunnel=%t recorded=%t",
			when, obs.tunnelEndpointOK, obs.endpointMatches)
	}
	if !obs.dialect.allMatch() {
		t.Fatalf("%s: the negative's dialect differs from the deployed one, so its failure "+
			"would not be attributable to the missing payload: %s", when, obs.diagnosis())
	}
	if !obs.counters.handshakeObserved {
		t.Fatalf("%s: the negative never completed a handshake, so it does not prove that the "+
			"payload is what failed: %s", when, obs.diagnosis())
	}
	if obs.canaryErr == nil {
		t.Fatalf("%s: the production canary accepted a peer that never answers", when)
	}
}

