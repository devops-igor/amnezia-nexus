// awgConsumerProbeTimeout bounds one canary attempt on the consumer path.
//
// The handler gives qualification one shared five second context for the outer probe and the
// canary, and the canary itself splits its budget between the primary ICMP attempt and the
// secondary DNS one. Three seconds leaves both attempts room inside that budget.
const awgConsumerProbeTimeout = 3 * time.Second

// awgConsumerDialect is the obfuscation dialect both sides agree on, as configured values.
//
// It is the identity dialect (jc=0, no padding, magic headers 1..4). The values are what the
// fixture writes into the server row and what it gives the peer, so the two can only agree if
// production carries the row's parameters all the way to the device.
func awgConsumerDialect() map[string]any {
	return map[string]any{
		"jc": 0, "jmin": 0, "jmax": 0, "s1": 0, "s2": 0, "s3": 0, "s4": 0,
		"h1": 1, "h2": 2, "h3": 3, "h4": 4,
	}
}

// awgConsumerDialectKeys is the ordered key list the capture reports on, so a failure names
// every mismatched key rather than the first one it found.
var awgConsumerDialectKeys = []string{
	"jc", "jmin", "jmax", "s1", "s2", "s3", "s4", "h1", "h2", "h3", "h4",
}

// purchaseCounter records purchase-path calls and refuses them, so "zero purchases" is a fact
// from the process that would have made them rather than an inference.
type purchaseCounter struct{ n atomic.Int64 }

func newPurchaseCounter() *purchaseCounter { return &purchaseCounter{} }

func (p *purchaseCounter) refuse(
	context.Context, gigahost.OrderRequest,
) (*gigahost.OrderResponse, error) {
	p.n.Add(1)
	return nil, errFixturePurchaseRefused
}

func (p *purchaseCounter) load() int64 { return p.n.Load() }

// awgConsumerPeer is a real amneziawg server device whose client peers are registered through
// the production provider contract during enablement.
type awgConsumerPeer struct {
	// endpoint is host:port the production client device dials.
	endpoint string
	// port is the same port as a number, for the server row and the approval.
	port int
	// serverPublicKey is the base64 key the client must target.
	serverPublicKey string

	dev      *device.Device
	pingConn *netstack.PingConn

	mu sync.Mutex
	// registered counts AddClient calls, so the provider contract is observable.
	registered int
	// clientPeers holds the keys already written to the device, so a repeated enablement
	// updates a peer instead of failing on a duplicate section.
	clientPeers map[string]struct{}

	stopOnce sync.Once
}

// startAWGConsumerPeer builds a real AWG server reachable on a loopback UDP port.
//
// It starts with NO client peer, because the client identity does not exist until the tunnel
// pool generates it. The peer's stack owns the canary destination when answerCanary is true;
// otherwise it owns an unrelated address, so the handshake and the transport still complete
// while the payload is never answered.
func startAWGConsumerPeer(t *testing.T, answerCanary bool) *awgConsumerPeer {
	t.Helper()

	serverPriv, serverPub := newAWGKeypair(t)

	canaryAddr := netip.MustParseAddr("1.1.1.1")
	stackAddrs := []netip.Addr{canaryAddr}
	if !answerCanary {
		stackAddrs = []netip.Addr{netip.MustParseAddr("10.99.99.99")}
	}
	tunDev, stack, err := netstack.CreateNetTUN(stackAddrs, nil, 1280)
	if err != nil {
		t.Fatalf("create AWG consumer peer netstack: %v", err)
	}
	// A real ICMP endpoint inside the peer's own stack is what answers the canary; there is
	// no userland copy of the reply anywhere.
	pingConn, err := stack.ListenPingAddr(canaryAddr)
	if err != nil {
		_ = tunDev.Close()
		t.Fatalf("consumer peer ICMP endpoint on the canary address: %v", err)
	}

	dev := device.NewDevice(tunDev, conn.NewDefaultBind(),
		device.NewLogger(device.LogLevelSilent, "awg-consumer-peer"))

	// Reserve a loopback UDP port, then release it: the engine binds its own socket in Up().
	probe, err := net.ListenUDP("udp", &net.UDPAddr{IP: net.ParseIP("127.0.0.1")})
	if err != nil {
		_ = pingConn.Close()
		dev.Close()
		t.Fatalf("consumer peer udp listen: %v", err)
	}
	port := probe.LocalAddr().(*net.UDPAddr).Port
	_ = probe.Close()

	if err := dev.IpcSet(buildAWGConsumerPeerIPC(serverPriv, port)); err != nil {
		_ = pingConn.Close()
		dev.Close()
		t.Fatalf("consumer peer IpcSet: %v", err)
	}
	if err := dev.Up(); err != nil {
		_ = pingConn.Close()
		dev.Close()
		t.Fatalf("consumer peer Up: %v", err)
	}

	peer := &awgConsumerPeer{
		endpoint:        fmt.Sprintf("127.0.0.1:%d", port),
		port:            port,
		serverPublicKey: serverPub,
		dev:             dev,
		pingConn:        pingConn,
		clientPeers:     map[string]struct{}{},
	}
	t.Cleanup(peer.stop)
	return peer
}

// stop tears the peer down exactly once.
func (p *awgConsumerPeer) stop() {
	if p == nil {
		return
	}
	p.stopOnce.Do(func() {
		if p.pingConn != nil {
			_ = p.pingConn.Close()
		}
		// device.Close() closes the TUN it was built on; closing that TUN again would
		// double-close the netstack's event channel and panic.
		if p.dev != nil {
			p.dev.Close()
		}
	})
}

// addClientPeer writes one client public key into the running peer, which is what the
// production provider contract does on a real backend.
//
// WireGuard's UAPI addresses a peer by its public key, so writing the same key again updates
// that peer in place. That is the idempotence the production registration relies on, and the
// repeated-pass assertions depend on it holding here too.
func (p *awgConsumerPeer) addClientPeer(publicKeyBase64 string, allowedIPs ...string) error {
	hexKey := base64ToHexKey(publicKeyBase64)
	if hexKey == "" {
		return errors.New("client public key is not a decodable 32-byte key")
	}
	var b strings.Builder
	fmt.Fprintf(&b, "public_key=%s\n", hexKey)
	for _, cidr := range allowedIPs {
		if cidr != "" {
			fmt.Fprintf(&b, "allowed_ip=%s\n", cidr)
		}
	}
	if err := p.dev.IpcSet(b.String()); err != nil {
		return err
	}
	p.mu.Lock()
	p.clientPeers[hexKey] = struct{}{}
	p.registered++
	p.mu.Unlock()
	return nil
}

// peerCount reports how many distinct client peers the device carries.
func (p *awgConsumerPeer) peerCount() int {
	p.mu.Lock()
	defer p.mu.Unlock()
	return len(p.clientPeers)
}

// registrations reports how many AddClient calls the provider received.
func (p *awgConsumerPeer) registrations() int {
	p.mu.Lock()
	defer p.mu.Unlock()
	return p.registered
}

// awgConsumerProvider is the AWG status provider the service uses for a backend.
//
// It answers the status query and implements the AddClient capability the production
// enablement path uses to register the portal's peers, which is how the real peer in this
// fixture learns the client identity that the tunnel pool generated a moment earlier.
type awgConsumerProvider struct {
	peer *awgConsumerPeer
}

func (p *awgConsumerProvider) GetServerStatus(context.Context, *models.Server) (map[string]any, error) {
	return map[string]any{
		"container_running": true,
		"public_key":        p.peer.serverPublicKey,
		"port":              p.peer.port,
	}, nil
}

// AddClient registers one client identity on the live peer.
//
// The production contract passes the portal's two identities with their AllowedIPs. A peer
// without allowed_ips keeps the default host scope, which is what the health-probe identity
// uses; the data identity must be scoped to the portal subnet so canary traffic from it is
// accepted here and replies route back.
func (p *awgConsumerProvider) AddClient(
	_ context.Context, _ *models.Server, clientParams map[string]any,
) (map[string]any, error) {
	pub, _ := clientParams["public_key"].(string)
	if pub == "" {
		pub, _ = clientParams["client_public_key"].(string)
	}
	if pub == "" {
		return nil, errors.New("no client public key in the provider request")
	}
	allowed, _ := clientParams["allowed_ips"].(string)
	if err := p.peer.addClientPeer(pub, allowed); err != nil {
		return nil, err
	}
	if allowed == "" {
		return map[string]any{"public_key": pub}, nil
	}
	return map[string]any{"public_key": pub, "allowed_ips": allowed}, nil
}

// buildAWGConsumerPeerIPC renders the server-side UAPI configuration with no client peer.
//
// The dialect is the one the fixture also records on the server row, so a client that carries
// the row's parameters through to its device speaks the same dialect this peer accepts.
func buildAWGConsumerPeerIPC(serverPrivBase64 string, listenPort int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "private_key=%s\n", base64ToHexKey(serverPrivBase64))
	fmt.Fprintf(&b, "listen_port=%d\n", listenPort)
	fmt.Fprintf(&b, "jc=0\njmin=0\njmax=0\n")
	fmt.Fprintf(&b, "s1=0\ns2=0\ns3=0\ns4=0\n")
	fmt.Fprintf(&b, "h1=1\nh2=2\nh3=3\nh4=4\n")
	return b.String()
}

// installAWGConsumerDialect gives the fixture's protocol manager an installation that records
// what a real AWG installation records: the server's public key, its port, and the wire
// parameters it deployed.
//
// This is the fixture-wiring correction the checkpoint permits. The shared install stub writes
// only "installed" and a port, so production reads no parameters and renders its own defaults
// - jc=1 - while the peer is pinned to jc=0. A client whose initiation carries junk the peer
// does not expect never completes a handshake, and the socket still reports transmitted bytes,
// which is precisely a healthy-looking attachment with a canary that never returns. Recording
// the deployed dialect is what a real install does; it is not a production change.
func installAWGConsumerDialect(env *installEnv, peer *awgConsumerPeer) {
	env.t.Helper()
	base := env.counters.installFnFor(models.ProtocolAWG)
	mgr, ok := env.h.registry.Get(models.ProtocolAWG)
	if !ok {
		env.t.Fatal("no AWG protocol manager is registered")
	}
	fixture, ok := mgr.(*mockProtocolManager)
	if !ok {
		env.t.Fatalf("AWG manager is %T, want the fixture manager", mgr)
	}
	fixture.installFn = func(ctx context.Context, server *models.Server, params map[string]any) error {
		if err := base(ctx, server, params); err != nil {
			return err
		}
		meta, _ := server.Protocols[models.ProtocolAWG].(map[string]any)
		if meta == nil {
			return errors.New("the install did not record the AWG protocol")
		}
		meta["public_key"] = peer.serverPublicKey
		meta["port"] = strconv.Itoa(peer.port)
		meta["awg_params"] = awgConsumerDialect()
		return nil
	}
}

// awgDialectReport is the per-key equality result between the device production built and the
// dialect the fixture deployed.
type awgDialectReport struct {
	match map[string]bool
	// missing lists keys the device did not report at all. The engine omits zero values, so
	// an absent key is compared against the engine's zero default rather than treated as a
	// missing observation.
	missing []string
}

// allMatch reports whether every key agreed.
func (r awgDialectReport) allMatch() bool {
	for _, k := range awgConsumerDialectKeys {
		if !r.match[k] {
			return false
		}
	}
	return true
}

// mismatched names every disagreeing key, so one failure identifies the whole divergence.
func (r awgDialectReport) mismatched() []string {
	var out []string
	for _, k := range awgConsumerDialectKeys {
		if !r.match[k] {
			out = append(out, k)
		}
	}
	return out
}

// compareAWGDialect compares the dialect on the device's own UAPI dump with the dialect the
// fixture deployed and gave the peer.
//
// Only booleans leave this function. The dump itself is never logged, and the values are
// compared, not echoed.
func compareAWGDialect(ipc string) awgDialectReport {
	want := awgConsumerDialect()
	got := map[string]string{}
	for _, line := range splitLines(ipc) {
		eq := strings.IndexByte(line, '=')
		if eq <= 0 {
			continue
		}
		got[line[:eq]] = line[eq+1:]
	}
	report := awgDialectReport{match: make(map[string]bool, len(awgConsumerDialectKeys))}
	for _, key := range awgConsumerDialectKeys {
		// The engine prints a knob only when it is non-zero, so a key absent from the dump
		// is the engine's zero value - which is what jc=0 and the padding keys mean here.
		value, present := got[key]
		if !present {
			report.missing = append(report.missing, key)
			value = "0"
		}
		report.match[key] = strings.TrimSpace(value) == strings.TrimSpace(fmt.Sprint(want[key]))
	}
	return report
}

// awgDeviceCounters is the transport evidence the device itself reports.
type awgDeviceCounters struct {
	txPositive        bool
	rxPositive        bool
	handshakeObserved bool
	i1Present         bool
}

// readAWGDeviceCounters extracts the presence booleans from a device UAPI dump.
//
// It reports presence, never values: whether the device transmitted, whether anything came
// back, whether a handshake completed, and whether the production data-plane preamble is
// configured.
func readAWGDeviceCounters(ipc string) awgDeviceCounters {
	var out awgDeviceCounters
	for _, line := range splitLines(ipc) {
		switch {
		case strings.HasPrefix(line, "tx_bytes="):
			out.txPositive = positiveCounter(line)
		case strings.HasPrefix(line, "rx_bytes="):
			out.rxPositive = positiveCounter(line)
		case strings.HasPrefix(line, "last_handshake_time_sec="):
			out.handshakeObserved = positiveCounter(line)
		case strings.HasPrefix(line, "i1="):
			out.i1Present = strings.TrimSpace(strings.TrimPrefix(line, "i1=")) != ""
		}
	}
	return out
}

// positiveCounter reports whether a "<key>=<int>" line carries a non-zero value.
func positiveCounter(line string) bool {
	eq := strings.IndexByte(line, '=')
	if eq <= 0 {
		return false
	}
	n, err := strconv.ParseInt(strings.TrimSpace(line[eq+1:]), 10, 64)
	return err == nil && n > 0
}

// awgConsumerObservation is what the capture records before the failure path rolls back.
//
// Everything in it is a boolean or a count of non-secret events, which is what may enter a
// test log: no raw configuration, no key material, no addresses.
type awgConsumerObservation struct {
	captured          bool
	deviceFound       bool
	deviceIsAWGDevice bool
	endpointMatches   bool
	tunnelEndpointOK  bool
	dialect           awgDialectReport
	counters          awgDeviceCounters
	canaryErr         error
}

// summary renders the observation for a log line.
func (o awgConsumerObservation) summary() string {
	return fmt.Sprintf(
		"captured=%t device_found=%t endpoint_matches=%t tunnel_endpoint_matches=%t "+
			"dialect_matches=%t dialect_mismatch=%v dialect_absent=%v i1_present=%t "+
			"tx_sent=%t rx_received=%t handshake_observed=%t canary_failed=%t",
		o.captured, o.deviceFound, o.endpointMatches, o.tunnelEndpointOK,
		o.dialect.allMatch(), o.dialect.mismatched(), o.dialect.missing, o.counters.i1Present,
		o.counters.txPositive, o.counters.rxPositive, o.counters.handshakeObserved,
		o.canaryErr != nil)
}

// diagnosis names the boundary a stalled or refused qualification points at, using only the
// non-secret observations. It is the decision table this checkpoint exists to make readable
// from a remote CI log:
//
//	dialect mismatch            -> the device was configured differently from the peer
//	endpoint mismatch           -> the device dialled something other than the fixture peer
//	no handshake, tx>0          -> the initiation was sent and dropped (dialect or endpoint)
//	no handshake, tx==0         -> nothing was even attempted
//	handshake, rx==0            -> the peer never answered the transport
//	handshake, rx>0, canary bad -> the payload was delivered but not answered
//	no device                   -> enablement never attached anything
func (o awgConsumerObservation) diagnosis() string {
	switch {
	case !o.deviceFound:
		return "no backend device was attached, so enablement never reached the data plane"
	case !o.deviceIsAWGDevice:
		return "the attached device is not the production AWG device"
	case !o.tunnelEndpointOK || !o.endpointMatches:
		return "the tunnel endpoint differs from the fixture peer endpoint"
	case !o.dialect.allMatch():
		return fmt.Sprintf("the device dialect differs from the deployed one (mismatch=%v absent=%v)",
			o.dialect.mismatched(), o.dialect.missing)
	case !o.counters.i1Present:
		return "the device carries no data-plane preamble, so the attachment did not apply it"
	case !o.counters.txPositive:
		return "the device transmitted nothing, so no handshake was even attempted"
	case !o.counters.handshakeObserved:
		return "traffic was sent but no handshake completed (initiation dropped)"
	case !o.counters.rxPositive:
		return "the handshake completed but nothing came back (transport unanswered)"
	case o.canaryErr != nil:
		return "the handshake and the transport completed but the payload was not answered"
	default:
		return "every observed boundary is healthy"
	}
}

// awgConsumerObservedDevice is the device surface this fixture reads.
//
// It is an interface over the production device so no test-only accessor is needed: the AWG
// device already exposes its UAPI dump, and the service already exposes the attached device
// and the endpoint it recorded for it.
type awgConsumerObservedDevice interface {
	DeviceIPC() (string, error)
}

// captureAWGConsumerStructure records the pre-rollback identity of the backend the handler
// qualified: which device was attached, which endpoint it carries, and which dialect it was
// configured with. It is read before the probe, because the dialect is what decides whether a
// probe can possibly complete.
func captureAWGConsumerStructure(
	svc *vpn.Service, tun *models.BackendTunnel, peer *awgConsumerPeer,
) awgConsumerObservation {
	obs := awgConsumerObservation{captured: true}
	if tun == nil {
		return obs
	}
	obs.tunnelEndpointOK = tun.Endpoint == peer.endpoint

	dev := svc.GetBackendDeviceForTest(tun.ID)
	if dev == nil {
		return obs
	}
	obs.deviceFound = true
	obs.endpointMatches = svc.GetBackendDeviceEndpointForTest(tun.ID) == peer.endpoint

	obsDev, ok := dev.(awgConsumerObservedDevice)
	if !ok {
		return obs
	}
	obs.deviceIsAWGDevice = true

	ipc, err := obsDev.DeviceIPC()
	if err != nil {
		return obs
	}
	obs.dialect = compareAWGDialect(ipc)
	return obs
}

// captureAWGConsumerCounters records the transport counters from the same attached device.
//
// It runs AFTER the probe attempt and still inside the canary seam, which is before the
// handler's failure branch disables the backend and closes the device. Reading them before the
// probe would report a healthy tunnel as silent: nothing has been sent until the canary writes
// its first packet.
func captureAWGConsumerCounters(
	svc *vpn.Service, tun *models.BackendTunnel, prev awgConsumerObservation,
) awgConsumerObservation {
	obs := prev
	if tun == nil || !prev.deviceIsAWGDevice {
		return obs
	}
	dev := svc.GetBackendDeviceForTest(tun.ID)
	if dev == nil {
		// The device was retired during the attempt. The structural evidence is still the
		// observation, and the missing counters stay false rather than being invented.
		return obs
	}
	obsDev, ok := dev.(awgConsumerObservedDevice)
	if !ok {
		return obs
	}
	ipc, err := obsDev.DeviceIPC()
	if err != nil {
		return obs
	}
	obs.counters = readAWGDeviceCounters(ipc)
	return obs
}

// installAWGConsumerCanary installs the capture into the canary seam and keeps the production
// verdict.
//
// The shared install fixture points the canary at a stub that returns success, and this
// checkpoint is about qualification, so the stub is cleared first and its absence is asserted:
// a silent override would make every assertion here vacuous. The seam then runs the same
// function the production default canary runs (`tunnel.ProbePacketDevice`) on the same
// attached device, and returns its error unchanged. There is no success path and no error
// swallow - only the observation is added.
func installAWGConsumerCanary(
	t *testing.T, env *installEnv, peer *awgConsumerPeer,
) *awgConsumerObservation {
	t.Helper()

	env.h.vpnSvc.SetCanaryProbeFunc(nil)
	// There is no accessor for the prober's override at this level, and one is not needed:
	// the capture below is the proof. If any override other than this one were answering,
	// `captured` would stay false and every assertion in this file would fail instead of
	// passing vacuously.

	obs := &awgConsumerObservation{}
	env.h.vpnSvc.SetCanaryProbeFunc(func(ctx context.Context, tun *models.BackendTunnel) error {
		structural := captureAWGConsumerStructure(env.h.vpnSvc, tun, peer)
		dev := env.h.vpnSvc.GetBackendDeviceForTest(tun.ID)
		if dev == nil {
			*obs = structural
			obs.canaryErr = errors.New("the backend has no attached device to probe")
			return obs.canaryErr
		}
		// The production probe, on the attached device, with the production subnet. Its
		// verdict is returned unchanged; only the observation is added.
		canaryErr := tunnel.ProbePacketDevice(
			ctx, dev, awgConsumerProbeTimeout, env.h.vpnSvc.SubnetCIDR())

		*obs = captureAWGConsumerCounters(env.h.vpnSvc, tun, structural)
		obs.canaryErr = canaryErr
		return canaryErr
	})
	return obs
}

