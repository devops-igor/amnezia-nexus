// Production-wired AWG peer for the automatic admission consumer.
//
// The component proof in gigahost_setup_awg_traffic_fixture_test.go builds the production
// device directly and hands it a dialect. That proves the engine, the obfuscation parameters
// and the canary, but it says nothing about the path a deployment actually takes. This
// fixture wires the same real peer into that path instead:
//
//	production entry -> tracker -> installer -> EnableBackendWithConfig
//	  -> resolveBackendCredentials(ctx, serverID, server)   (reads the server row)
//	  -> buildBackendDeviceParams                           (stored dialect + generated i1)
//	  -> tunnel.NewAWGClientDevice(name, tun.Endpoint, tun.PrivateKey, tun.PublicKey, ...)
//	  -> registerBackendPortalPeers -> awgProvider.AddClient  (peer learns the client identity)
//	  -> attachBackendForwarder -> pumpBackendReturns
//	  -> handlers.qualifyBackendTraffic -> ProbeTunnel -> ProbeCanary
//
// Two differences from the component proof are deliberate and are the reason this exists.
//
// First, the client's private key is generated by the tunnel pool, so it does not exist until
// enablement registers the tunnel. The peer therefore learns the client's public key the same
// way a real backend does - through the provider's AddClient call during enablement - rather
// than being pre-configured by the test.
//
// Second, the device parameters now come from the server row, which is what production reads.
// A real AWG installation records the wire parameters it deployed (that is what the manager's
// own install writes into the server row), so this fixture records the same dialect it gave
// the peer. Without that the row carries no dialect, production renders its defaults (jc=1),
// and a peer pinned to jc=0 never sees the initiation - the tunnel looks attached and the
// canary times out. That divergence is a fixture defect, not a product one, and the fixture
// records the dialect for exactly that reason.
//
// Everything captured here is observed BEFORE the failure path rolls the backend back, which
// is the point of the checkpoint: a stalled canary has to be diagnosable from the test log
// without a raw configuration dump.

